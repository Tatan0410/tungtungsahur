const { ClienteSQLite } = require('./src/db/cliente')
const { aplicarMigraciones } = require('./src/db/migraciones')
;(async () => {
  const db = new ClienteSQLite('C:/Users/sebas/AppData/Local/Temp/opencode/copia-fusion.db')
  console.log('migraciones aplicadas a la copia:', await aplicarMigraciones(db))
  const cols = await db.prepare('PRAGMA table_info(materias)').all()
  console.log('materias columnas:', cols.map(c => c.name + (c.notnull ? ' NN' : '')).join(', '))
  console.log('materias:', (await db.prepare('SELECT COUNT(*) AS c FROM materias').get()).c)
  console.log('fk restaurada:', db.pragma('foreign_keys', { simple: true }))
  await db.close()
})().catch(e => { console.error('FALLO:', e.message); process.exit(1) })
